const assert = require("assert/strict");
const adapter = require("./postgres-adapter");

async function testPostgreSQLAdapter() {
    const connected = await adapter.get("SELECT 1 AS connected");
    assert.equal(connected.connected, 1);

    const oneRow = await adapter.get("SELECT ?::integer AS value", [7]);
    assert.equal(Number(oneRow.value), 7);

    const multipleRows = await adapter.all(
        "SELECT value FROM (VALUES (?), (?)) AS values(value) ORDER BY value",
        [2, 1]
    );
    assert.deepEqual(multipleRows.map(row => Number(row.value)), [1, 2]);

    const quotedQuestion = await adapter.get(
        "SELECT '?' AS literal, ?::integer AS value",
        [9]
    );
    assert.equal(quotedQuestion.literal, "?");
    assert.equal(Number(quotedQuestion.value), 9);

    let committedResult;
    await adapter.transaction(async transaction => {
        await transaction.exec(`
            CREATE TEMP TABLE step_11b_adapter_test (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                label TEXT NOT NULL,
                enabled BOOLEAN NOT NULL,
                metadata JSONB
            ) ON COMMIT DROP
        `);

        const inserted = await transaction.run(
            "INSERT INTO step_11b_adapter_test (label, enabled, metadata) VALUES (?, ?, ?) RETURNING id, label, enabled, metadata",
            ["adapter-test", true, { source: "test" }]
        );
        assert.equal(inserted.changes, 1);
        assert.equal(inserted.lastInsertRowid, inserted.rows[0].id);
        assert.equal(inserted.rows[0].enabled, true);
        assert.deepEqual(inserted.rows[0].metadata, { source: "test" });

        const updated = await transaction.run(
            "UPDATE step_11b_adapter_test SET label = ? WHERE id = ?",
            ["adapter-test-updated", inserted.lastInsertRowid]
        );
        assert.equal(updated.changes, 1);

        const selected = await transaction.get(
            "SELECT label FROM step_11b_adapter_test WHERE id = ?",
            [inserted.lastInsertRowid]
        );
        assert.equal(selected.label, "adapter-test-updated");

        const deleted = await transaction.run(
            "DELETE FROM step_11b_adapter_test WHERE id = ?",
            [inserted.lastInsertRowid]
        );
        assert.equal(deleted.changes, 1);
        committedResult = true;
    });
    assert.equal(committedResult, true);

    await assert.rejects(
        adapter.transaction(async transaction => {
            await transaction.exec(`
                CREATE TEMP TABLE step_11b_adapter_rollback_test (value TEXT)
            `);
            await transaction.run(
                "INSERT INTO step_11b_adapter_rollback_test (value) VALUES (?)",
                ["rolled-back"]
            );
            throw new Error("intentional adapter rollback test");
        }),
        /intentional adapter rollback test/
    );

    const rollbackCheck = await adapter.get(
        "SELECT to_regclass('pg_temp.step_11b_adapter_rollback_test') AS table_name"
    );
    assert.equal(rollbackCheck.table_name, null);

    console.log("PostgreSQL adapter test successful.");
}

testPostgreSQLAdapter()
    .catch(error => {
        console.error("PostgreSQL adapter test failed:", error.message);
        process.exitCode = 1;
    })
    .finally(async () => {
        await adapter.pool.end();
    });
