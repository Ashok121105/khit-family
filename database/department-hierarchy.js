function normalizeRoleName(roleName) {
    return String(roleName || "").trim().toLowerCase();
}

async function ensurePostgresAuthorizationTables() {
    if (!usePostgres) return;
    await postgres.exec(`
        CREATE TABLE IF NOT EXISTS roles (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL UNIQUE,
            description TEXT,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS permissions (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            permission_key TEXT NOT NULL UNIQUE,
            description TEXT,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS role_permissions (
            role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
            permission_key TEXT NOT NULL,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (role_id, permission_key)
        );
        CREATE TABLE IF NOT EXISTS user_roles (
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
            is_primary BOOLEAN DEFAULT TRUE,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (user_id, role_id)
        );
        CREATE TABLE IF NOT EXISTS user_role_scopes (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
            scope TEXT NOT NULL,
            department_id BIGINT REFERENCES departments(id) ON DELETE CASCADE,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(user_id, role_id, department_id)
        );
        CREATE TABLE IF NOT EXISTS user_departments (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
            designation TEXT NOT NULL DEFAULT 'Faculty',
            role_name TEXT NOT NULL DEFAULT 'faculty',
            is_primary BOOLEAN NOT NULL DEFAULT TRUE,
            from_date TEXT,
            to_date TEXT,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(user_id, department_id, role_name)
        );
    `);
    for (const [name, description] of [
        ["hod", "Department head"], ["associate_hod", "Department associate head"],
        ["assistant_hod", "Department assistant head"], ["faculty", "Department faculty"],
        ["ao", "Administrative officer"], ["principal", "College principal"],
        ["director", "College director"], ["admin", "Administrative role"],
        ["superadmin", "Super administrator"]
    ]) await postgres.run("INSERT INTO roles (name, description) VALUES (?, ?) ON CONFLICT (name) DO NOTHING", [name, description]);
    const permissions = [...new Set([...CANONICAL_PERMISSIONS, ...Object.values(DEPARTMENT_ROLES).flat()])];
    for (const permission of permissions) {
        await postgres.run("INSERT INTO permissions (permission_key, description) VALUES (?, ?) ON CONFLICT (permission_key) DO NOTHING", [permission, permission]);
    }
    for (const [role, rolePermissions] of Object.entries(DEPARTMENT_ROLES)) {
        for (const permission of rolePermissions) {
            await postgres.run(`
                INSERT INTO role_permissions (role_id, permission_key)
                SELECT id, ? FROM roles WHERE name = ?
                ON CONFLICT DO NOTHING
            `, [permission, role]);
        }
    }
}

async function getUserDepartmentMembershipsAsync(userId) {
    if (!usePostgres) return getUserDepartmentMemberships(userId);
    return postgres.all(`
        SELECT ud.*, d.id AS department_id, d.code, d.name
        FROM user_departments ud JOIN departments d ON d.id = ud.department_id
        WHERE ud.user_id = ? AND (ud.to_date IS NULL OR ud.to_date::date >= CURRENT_DATE)
        ORDER BY ud.is_primary DESC, d.name ASC
    `, [userId]);
}

async function getRolePermissionsAsync(roleName) {
    if (!usePostgres) return getRolePermissions(roleName);
    const rows = await postgres.all(`
        SELECT rp.permission_key FROM role_permissions rp JOIN roles r ON r.id = rp.role_id
        WHERE r.name = ?
    `, [normalizeRoleName(roleName)]);
    return [...new Set(rows.map(row => row.permission_key).filter(Boolean))];
}

function getRoleScope(roleName) {
    const normalizedRole = normalizeRoleName(roleName);
    if (ROLE_SCOPE_MAP[normalizedRole]) {
        return ROLE_SCOPE_MAP[normalizedRole];
    }
    return "SELF";
}

function seedCanonicalRolesAndPermissions() {
    const rolesToSeed = [
        ["hod", "Department head"],
        ["associate_hod", "Department associate head"],
        ["assistant_hod", "Department assistant head"],
        ["faculty", "Department faculty"],
        ["ao", "Administrative officer"],
        ["principal", "College principal"],
        ["director", "College director"],
        ["student", "Student role"],
        ["parent", "Parent role"],
        ["admin", "Administrative role"],
        ["superadmin", "Super administrator role"]
    ];

    const insertRole = db.prepare(`INSERT OR IGNORE INTO roles (name, description) VALUES (?, ?)`);
    rolesToSeed.forEach(([name, description]) => insertRole.run(name, description));

    const insertPermission = db.prepare(`INSERT OR IGNORE INTO permissions (permission_key, description) VALUES (?, ?)`);
    const uniquePermissionList = [...new Set([...CANONICAL_PERMISSIONS, ...Object.values(DEPARTMENT_ROLES).flat()])];
    uniquePermissionList.forEach((permissionKey) => {
        insertPermission.run(permissionKey, permissionKey);
    });

    Object.entries(DEPARTMENT_ROLES).forEach(([roleName, permissions]) => {
        const roleRow = db.prepare(`SELECT id FROM roles WHERE name = ?`).get(roleName);
        if (!roleRow) return;
        permissions.forEach((permissionKey) => {
            db.prepare(`INSERT OR IGNORE INTO role_permissions (role_id, permission_key) VALUES (?, ?)`)
                .run(roleRow.id, permissionKey);
        });
    });
}

function getRolePermissions(roleName) {
    const normalizedRole = normalizeRoleName(roleName);
    const directPermissions = DEPARTMENT_ROLES[normalizedRole] || [];
    const roleRow = db.prepare(`SELECT id FROM roles WHERE name = ?`).get(normalizedRole);
    if (!roleRow) return directPermissions;

    const rows = db.prepare(`
        SELECT permission_key
        FROM role_permissions
        WHERE role_id = ?
    `).all(roleRow.id);

    const fromDb = rows.map((row) => row.permission_key).filter(Boolean);
    return [...new Set([...directPermissions, ...fromDb])];
}

function hasRolePermission(user, permissionKey) {
    if (!user || !permissionKey) return false;
    const normalizedPermission = String(permissionKey).trim();
    const normalizedRole = normalizeRoleName(user.role);
    if (!normalizedRole) return false;

    const permissions = getRolePermissions(normalizedRole);
    return permissions.includes(normalizedPermission);
}

function ensureDepartmentTableColumns() {
    const departmentsInfo = db.prepare(`PRAGMA table_info(departments)`).all();
    const departmentColumns = new Set(departmentsInfo.map((column) => column.name));

    const migrations = [
        ["created_at", "created_at DATETIME"],
        ["active", "active INTEGER NOT NULL DEFAULT 1"],
        ["head_of_department_user_id", "head_of_department_user_id INTEGER"],
        ["hod_user_id", "hod_user_id INTEGER"],
        ["updated_at", "updated_at DATETIME"]
    ];

    migrations.forEach(([columnName, definition]) => {
        if (departmentColumns.has(columnName)) return;

        db.exec(`ALTER TABLE departments ADD COLUMN ${definition}`);
        departmentColumns.add(columnName);

        if (columnName === "created_at") {
            db.prepare(`UPDATE departments SET created_at = CURRENT_TIMESTAMP WHERE created_at IS NULL`).run();
        }

        if (columnName === "active") {
            db.prepare(`UPDATE departments SET active = 1 WHERE active IS NULL`).run();
        }

        if (columnName === "updated_at") {
            db.prepare(`UPDATE departments SET updated_at = CURRENT_TIMESTAMP WHERE updated_at IS NULL`).run();
        }
    });
}

function ensureDepartmentHierarchyTables() {
    if (usePostgres) return;

    db.exec(`
        CREATE TABLE IF NOT EXISTS departments (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            code TEXT UNIQUE NOT NULL,
            name TEXT NOT NULL,
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP
        );

        CREATE TABLE IF NOT EXISTS user_departments (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER NOT NULL,
            department_id INTEGER NOT NULL,
            designation TEXT NOT NULL DEFAULT 'Faculty',
            role_name TEXT NOT NULL DEFAULT 'faculty',
            is_primary INTEGER NOT NULL DEFAULT 1,
            from_date TEXT,
            to_date TEXT,
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
            FOREIGN KEY(department_id) REFERENCES departments(id) ON DELETE CASCADE,
            UNIQUE(user_id, department_id, role_name)
        );
    `);

    ensureDepartmentTableColumns();

    seedCanonicalRolesAndPermissions();

    const defaultDepartments = [
        ["CSE", "Computer Science and Engineering"],
        ["ECE", "Electronics and Communication Engineering"],
        ["EEE", "Electrical and Electronics Engineering"],
        ["ME", "Mechanical Engineering"],
        ["CE", "Civil Engineering"]
    ];

    const insertDepartment = db.prepare(`
        INSERT OR IGNORE INTO departments (code, name, active, head_of_department_user_id, hod_user_id, created_at, updated_at)
        VALUES (?, ?, 1, NULL, NULL, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
    `);
    defaultDepartments.forEach(([code, name]) => insertDepartment.run(code, name));

    const facultyRows = db.prepare(`SELECT id, user_id, department, designation FROM faculty WHERE department IS NOT NULL`).all();
    facultyRows.forEach((facultyRow) => {
        const departmentRow = resolveDepartmentByNameOrCode(facultyRow.department);
        if (!departmentRow || !facultyRow.user_id) return;
        upsertUserDepartment(facultyRow.user_id, departmentRow.id, facultyRow.designation || "Faculty", "faculty", 1, null, null);
    });

    const usersTableInfo = db.prepare(`PRAGMA table_info(users)`).all();
    const hasUserDepartmentColumn = usersTableInfo.some((column) => column.name === "department");

    if (hasUserDepartmentColumn) {
        const userRows = db.prepare(`SELECT id, role, department FROM users WHERE role IN ('hod', 'associate_hod', 'assistant_hod')`).all();
        userRows.forEach((userRow) => {
            const departmentRow = resolveDepartmentByNameOrCode(userRow.department || "");
            if (!departmentRow) return;
            upsertUserDepartment(userRow.id, departmentRow.id, userRow.role, userRow.role, 1, null, null);
        });
    }
}

function resolveDepartmentByNameOrCode(value) {
    const raw = String(value || "").trim();
    if (!raw) return null;

    if (usePostgres) {
        return postgres.get(`
            SELECT *
            FROM departments
            WHERE code = ? OR name = ?
            ORDER BY id ASC
            LIMIT 1
        `, [raw, raw])
            || postgres.get(`SELECT * FROM departments WHERE name ILIKE ? LIMIT 1`, [`%${raw}%`]);
    }

    return db.prepare(`
        SELECT *
        FROM departments
        WHERE code = ? OR name = ?
        ORDER BY id ASC
        LIMIT 1
    `).get(raw, raw)
        || db.prepare(`SELECT * FROM departments WHERE name LIKE ? LIMIT 1`).get(`%${raw}%`);
}

async function upsertUserDepartmentAsync(userId, departmentId, designation, roleName, isPrimary = 1, fromDate = null, toDate = null) {
    if (usePostgres) {
        const normalizedRoleName = String(roleName || "faculty").trim();
        const row = await postgres.get(`
            SELECT *
            FROM user_departments
            WHERE user_id = ? AND department_id = ? AND role_name = ?
            LIMIT 1
        `, [userId, departmentId, normalizedRoleName]);

        if (row) {
            await postgres.run(`
                UPDATE user_departments
                SET designation = ?, is_primary = ?, from_date = COALESCE(?, from_date), to_date = COALESCE(?, to_date)
                WHERE id = ?
            `, [designation || row.designation || "Faculty", Number(isPrimary) ? true : false, fromDate || row.from_date || null, toDate || row.to_date || null, row.id]);
            return await postgres.get(`SELECT * FROM user_departments WHERE id = ?`, [row.id]);
        }

        const result = await postgres.run(`
            INSERT INTO user_departments (user_id, department_id, designation, role_name, is_primary, from_date, to_date, created_at)
            VALUES (?, ?, ?, ?, ?, ?, ?, NOW())
            RETURNING id
        `, [userId, departmentId, designation || "Faculty", normalizedRoleName, Number(isPrimary) ? true : false, fromDate || null, toDate || null]);

        return await postgres.get(`SELECT * FROM user_departments WHERE id = ?`, [result.lastInsertRowid || result.rows?.[0]?.id]);
    }

    return upsertUserDepartment(userId, departmentId, designation, roleName, isPrimary, fromDate, toDate);
}

function upsertUserDepartment(userId, departmentId, designation, roleName, isPrimary = 1, fromDate = null, toDate = null) {
    if (usePostgres) {
        const normalizedRoleName = String(roleName || "faculty").trim();
        const fallback = postgres.get(`
            SELECT *
            FROM user_departments
            WHERE user_id = ? AND department_id = ? AND role_name = ?
            LIMIT 1
        `, [userId, departmentId, normalizedRoleName]).then(async (row) => {
            if (row) {
                await postgres.run(`
                    UPDATE user_departments
                    SET designation = ?, is_primary = ?, from_date = COALESCE(?, from_date), to_date = COALESCE(?, to_date)
                    WHERE id = ?
                `, [designation || row.designation || "Faculty", Number(isPrimary) ? true : false, fromDate || row.from_date || null, toDate || row.to_date || null, row.id]);
                return row;
            }

            const result = await postgres.run(`
                INSERT INTO user_departments (user_id, department_id, designation, role_name, is_primary, from_date, to_date, created_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, NOW())
                RETURNING id
            `, [userId, departmentId, designation || "Faculty", normalizedRoleName, Number(isPrimary) ? true : false, fromDate || null, toDate || null]);
            return postgres.get(`SELECT * FROM user_departments WHERE id = ?`, [result.lastInsertRowid || result.rows?.[0]?.id]);
        }).catch((error) => {
            console.error("upsertUserDepartment PG error:", error.message);
            return null;
        });
        return fallback;
    }

    const row = db.prepare(`
        SELECT *
        FROM user_departments
        WHERE user_id = ? AND department_id = ? AND role_name = ?
        LIMIT 1
    `).get(userId, departmentId, roleName);

    if (row) {
        db.prepare(`
            UPDATE user_departments
            SET designation = ?, is_primary = ?, from_date = COALESCE(?, from_date), to_date = COALESCE(?, to_date)
            WHERE id = ?
        `).run(designation || row.designation || "Faculty", Number(isPrimary) ? 1 : 0, fromDate || row.from_date || null, toDate || row.to_date || null, row.id);
        return row;
    }

    const result = db.prepare(`
        INSERT INTO user_departments (user_id, department_id, designation, role_name, is_primary, from_date, to_date, created_at)
        VALUES (?, ?, ?, ?, ?, ?, ?, CURRENT_TIMESTAMP)
    `).run(
        userId,
        departmentId,
        designation || "Faculty",
        roleName || "faculty",
        Number(isPrimary) ? 1 : 0,
        fromDate || null,
        toDate || null
    );

    return db.prepare(`SELECT * FROM user_departments WHERE id = ?`).get(result.lastInsertRowid);
}

function getUserDepartmentMemberships(userId) {
    if (usePostgres) {
        const rows = postgres.all(`
            SELECT ud.*, d.id AS department_id, d.code, d.name
            FROM user_departments ud
            JOIN departments d ON d.id = ud.department_id
            WHERE ud.user_id = ?
              AND (ud.to_date IS NULL OR ud.to_date::date >= CURRENT_DATE)
            ORDER BY ud.is_primary DESC, d.name ASC
        `, [userId]);
        return rows;
    }

    return db.prepare(`
        SELECT ud.*, d.id AS department_id, d.code, d.name
        FROM user_departments ud
        JOIN departments d ON d.id = ud.department_id
        WHERE ud.user_id = ?
          AND d.active = 1
          AND (ud.to_date IS NULL OR ud.to_date >= date('now'))
        ORDER BY ud.is_primary DESC, d.name ASC
    `).all(userId);
}

function getDepartmentAccessForUser(user) {
    if (!user || !user.id) return { allowed: false, memberships: [], role: user?.role || null };
    const memberships = getUserDepartmentMemberships(user.id);
    return {
        allowed: true,
        memberships,
        role: user.role || null,
        departmentIds: memberships.map((row) => Number(row.department_id))
    };
}

async function getUserDepartmentMembershipsAsync(userId) {
    if (!usePostgres) return getUserDepartmentMemberships(userId);
    return postgres.all(`
        SELECT ud.*, d.id AS department_id, d.code, d.name
        FROM user_departments ud JOIN departments d ON d.id = ud.department_id
        WHERE ud.user_id = ? AND (ud.to_date IS NULL OR ud.to_date::date >= CURRENT_DATE)
        ORDER BY ud.is_primary DESC, d.name ASC
    `, [userId]);
}

function canAccessDepartment(user, targetDepartmentId, requiredPermission) {
    if (!user) return false;
    if (user.role === "admin" || user.role === "superadmin") return true;

    const userScope = String(user.scope || getRoleScope(user.role)).toUpperCase();
    if (userScope === "COLLEGE_WIDE" || userScope === "SYSTEM") {
        if (!requiredPermission) return true;
        return hasRolePermission(user, requiredPermission);
    }

    const departmentId = Number(targetDepartmentId);
    if (!departmentId) return false;

    const memberships = getUserDepartmentMemberships(user.id);
    if (!memberships.length) {
        return user.role === "faculty";
    }

    const isMember = memberships.some((membership) => Number(membership.department_id) === departmentId);
    if (!isMember) return false;

    if (!requiredPermission) return true;

    const rolePermissions = getRolePermissions(user.role);
    return rolePermissions.includes(requiredPermission);
}

function ensureFacultyDepartmentAssignment(userId, departmentName, designation = "Faculty") {
    const departmentRow = resolveDepartmentByNameOrCode(departmentName);
    if (!departmentRow || !userId) return null;
    return upsertUserDepartment(userId, departmentRow.id, designation, "faculty", 1, null, null);
}

