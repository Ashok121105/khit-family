function ensureParentFamilyTables() {
    db.exec(`
        CREATE TABLE IF NOT EXISTS roles (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT UNIQUE NOT NULL,
            description TEXT,
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP
        );

        CREATE TABLE IF NOT EXISTS permissions (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            permission_key TEXT UNIQUE NOT NULL,
            description TEXT,
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP
        );

        CREATE TABLE IF NOT EXISTS role_permissions (
            role_id INTEGER NOT NULL,
            permission_key TEXT NOT NULL,
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (role_id, permission_key),
            FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE
        );

        CREATE TABLE IF NOT EXISTS user_roles (
            user_id INTEGER NOT NULL,
            role_id INTEGER NOT NULL,
            is_primary INTEGER DEFAULT 1,
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (user_id, role_id),
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
            FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE
        );

        CREATE TABLE IF NOT EXISTS user_role_scopes (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER NOT NULL,
            role_id INTEGER NOT NULL,
            scope TEXT NOT NULL,
            department_id INTEGER,
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(user_id, role_id, department_id),
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
            FOREIGN KEY(role_id) REFERENCES roles(id) ON DELETE CASCADE
        );

        CREATE TABLE IF NOT EXISTS parents (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            full_name TEXT,
            mobile TEXT UNIQUE,
            email TEXT UNIQUE,
            otp_verified INTEGER DEFAULT 0,
            status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active', 'inactive', 'pending', 'blocked')),
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
            updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
        );

        CREATE TABLE IF NOT EXISTS parent_student_links (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            parent_id INTEGER NOT NULL,
            student_id INTEGER NOT NULL,
            relationship_type TEXT NOT NULL DEFAULT 'Guardian' CHECK(relationship_type IN ('Father', 'Mother', 'Guardian')),
            is_primary INTEGER NOT NULL DEFAULT 1,
            status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active', 'inactive', 'blocked')),
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
            updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(parent_id, student_id),
            FOREIGN KEY(parent_id) REFERENCES parents(id) ON DELETE CASCADE,
            FOREIGN KEY(student_id) REFERENCES students(id) ON DELETE CASCADE
        );

        CREATE TABLE IF NOT EXISTS parent_otp_verifications (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            parent_id INTEGER NOT NULL,
            otp_hash TEXT NOT NULL,
            purpose TEXT NOT NULL CHECK(purpose IN ('registration verification', 'login', 'mobile change')),
            expires_at DATETIME NOT NULL,
            attempts INTEGER NOT NULL DEFAULT 0,
            used_at DATETIME,
            created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY(parent_id) REFERENCES parents(id) ON DELETE CASCADE
        );
    `);

    const otpColumns = new Set(db.prepare(`PRAGMA table_info(parent_otp_verifications)`).all().map((column) => column.name));
    if (!otpColumns.has("attempts")) {
        db.exec(`ALTER TABLE parent_otp_verifications ADD COLUMN attempts INTEGER NOT NULL DEFAULT 0`);
    }

    db.exec(`
        CREATE UNIQUE INDEX IF NOT EXISTS idx_parents_mobile_unique ON parents(mobile) WHERE mobile IS NOT NULL;
        CREATE UNIQUE INDEX IF NOT EXISTS idx_parents_email_unique ON parents(email) WHERE email IS NOT NULL;
        CREATE INDEX IF NOT EXISTS idx_parent_student_links_parent ON parent_student_links(parent_id);
        CREATE INDEX IF NOT EXISTS idx_parent_student_links_student ON parent_student_links(student_id);
        CREATE INDEX IF NOT EXISTS idx_parent_otp_parent ON parent_otp_verifications(parent_id, purpose, expires_at);
    `);

    const defaultRoles = [
        ["student", "Default student role"],
        ["parent", "Parent role with student-linked access"],
        ["faculty", "Faculty role"],
        ["admin", "Administrative role"],
        ["superadmin", "Super administrator role"]
    ];

    const defaultPermissions = [
        ["student.self.read", "Read own student profile"],
        ["parent.linked_student.read", "Read linked student data"],
        ["parent.linked_student.update", "Update linked student data"],
        ["faculty.department.read", "Read department data"],
        ["admin.college.write", "Write college-level data"]
    ];

    const insertRole = db.prepare(`INSERT OR IGNORE INTO roles (name, description) VALUES (?, ?)`);
    const insertPermission = db.prepare(`INSERT OR IGNORE INTO permissions (permission_key, description) VALUES (?, ?)`);

    defaultRoles.forEach(([name, description]) => insertRole.run(name, description));
    defaultPermissions.forEach(([key, description]) => insertPermission.run(key, description));

    const parentRoleId = db.prepare(`SELECT id FROM roles WHERE name = 'parent'`).get()?.id;
    if (parentRoleId) {
        const permissionKeys = ["parent.linked_student.read", "parent.linked_student.update"];
        permissionKeys.forEach((permissionKey) => {
            const permissionId = db.prepare(`SELECT id FROM permissions WHERE permission_key = ?`).get(permissionKey)?.id;
            if (permissionId) {
                db.prepare(`INSERT OR IGNORE INTO role_permissions (role_id, permission_key) VALUES (?, ?)`)
                    .run(parentRoleId, permissionKey);
            }
        });
    }
}

function getLegacyParentRecords() {
    return db.prepare(`
        SELECT id, parent_name, parent_mobile, parent_email
        FROM students
        WHERE (
            TRIM(COALESCE(parent_name, '')) <> '' OR
            TRIM(COALESCE(parent_mobile, '')) <> '' OR
            TRIM(COALESCE(parent_email, '')) <> ''
        )
    `).all();
}

function insertOrGetParent({ fullName, mobile, email }) {
    const parentMobile = normalizeParentMobile(mobile);
    const parentEmail = normalizeParentEmail(email);

    if (!parentMobile && !parentEmail) {
        return null;
    }

    let parent = null;
    if (parentMobile) {
        parent = db.prepare(`SELECT * FROM parents WHERE mobile = ?`).get(parentMobile);
    }

    if (!parent && parentEmail) {
        parent = db.prepare(`SELECT * FROM parents WHERE email = ?`).get(parentEmail);
    }

    if (!parent) {
        const result = db.prepare(`
            INSERT INTO parents (full_name, mobile, email, otp_verified, status, created_at, updated_at)
            VALUES (?, ?, ?, 0, 'active', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
        `).run(
            fullName || null,
            parentMobile || null,
            parentEmail || null
        );

        parent = db.prepare(`SELECT * FROM parents WHERE id = ?`).get(result.lastInsertRowid);
    } else {
        const existingName = parent.full_name || fullName || null;
        db.prepare(`
            UPDATE parents
            SET full_name = COALESCE(?, full_name),
                mobile = COALESCE(?, mobile),
                email = COALESCE(?, email),
                updated_at = CURRENT_TIMESTAMP
            WHERE id = ?
        `).run(existingName || null, parentMobile || parent.mobile || null, parentEmail || parent.email || null, parent.id);
        parent = db.prepare(`SELECT * FROM parents WHERE id = ?`).get(parent.id);
    }

    return parent;
}

function ensureParentLink(parentId, studentId, relationshipType = "Guardian", isPrimary = 1) {
    if (!parentId || !studentId) return null;

    const normalizedRelationship = normalizeRelationshipType(relationshipType);
    const existing = db.prepare(`
        SELECT * FROM parent_student_links
        WHERE parent_id = ? AND student_id = ?
    `).get(parentId, studentId);

    if (existing) {
        db.prepare(`
            UPDATE parent_student_links
            SET relationship_type = ?, is_primary = ?, status = 'active', updated_at = CURRENT_TIMESTAMP
            WHERE parent_id = ? AND student_id = ?
        `).run(normalizedRelationship, Number(isPrimary) ? 1 : 0, parentId, studentId);
        return db.prepare(`SELECT * FROM parent_student_links WHERE parent_id = ? AND student_id = ?`).get(parentId, studentId);
    }

    const result = db.prepare(`
        INSERT INTO parent_student_links (parent_id, student_id, relationship_type, is_primary, status, created_at, updated_at)
        VALUES (?, ?, ?, ?, 'active', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
    `).run(parentId, studentId, normalizedRelationship, Number(isPrimary) ? 1 : 0);

    return db.prepare(`SELECT * FROM parent_student_links WHERE id = ?`).get(result.lastInsertRowid);
}

function migrateLegacyParentData() {
    const students = getLegacyParentRecords();

    students.forEach((student) => {
        const parent = insertOrGetParent({
            fullName: student.parent_name,
            mobile: student.parent_mobile,
            email: student.parent_email
        });

        if (!parent || !student.id) return;
        ensureParentLink(parent.id, student.id, "Guardian", 1);
    });
}

