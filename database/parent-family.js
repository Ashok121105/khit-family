async function verifyParentOtp(parentId, otp, purpose) {
    const record = db.prepare(`
        SELECT *
        FROM parent_otp_verifications
        WHERE parent_id = ? AND purpose = ? AND used_at IS NULL
        ORDER BY id DESC
        LIMIT 1
    `).get(parentId, purpose);

    if (!record) {
        return { valid: false, reason: "no_active_otp" };
    }

    if (Number(record.attempts || 0) >= 5) {
        db.prepare(`UPDATE parent_otp_verifications SET used_at = CURRENT_TIMESTAMP WHERE id = ?`).run(record.id);
        return { valid: false, reason: "attempt_limit" };
    }

    const now = Date.now();
    const expiresAt = new Date(record.expires_at).getTime();

    if (expiresAt < now) {
        db.prepare(`UPDATE parent_otp_verifications SET used_at = CURRENT_TIMESTAMP WHERE id = ?`).run(record.id);
        return { valid: false, reason: "expired_otp" };
    }

    const isMatch = await bcrypt.compare(String(otp || "").trim(), record.otp_hash);
    if (!isMatch) {
        db.prepare(`UPDATE parent_otp_verifications SET attempts = attempts + 1 WHERE id = ?`).run(record.id);
        return { valid: false, reason: "invalid_otp" };
    }

    db.prepare(`UPDATE parent_otp_verifications SET used_at = CURRENT_TIMESTAMP WHERE id = ?`).run(record.id);
    db.prepare(`UPDATE parents SET otp_verified = 1, updated_at = CURRENT_TIMESTAMP WHERE id = ?`).run(parentId);
    return { valid: true, reason: "ok" };
}

