const bcrypt = require("bcryptjs");
const db = require("./database");
const postgres = require("./postgres-adapter");

const usePostgres = Boolean(process.env.DATABASE_URL);

function normalizeParentMobile(value) {
    if (value === null || value === undefined) return null;
    const cleaned = String(value).trim();
    if (!cleaned) return null;
    const digits = cleaned.replace(/[^0-9+]/g, "");
    if (!digits) return null;
    return digits.startsWith("+") ? digits : digits.replace(/^00/, "").replace(/^0+/, "");
}

function normalizeParentEmail(value) {
    if (value === null || value === undefined) return null;
    const cleaned = String(value).trim();
    return cleaned ? cleaned.toLowerCase() : null;
}

function normalizeRelationshipType(value) {
    const relationship = String(value || "Guardian").trim();
    const normalized = relationship.toLowerCase();
    if (["father", "dad", "male parent"].includes(normalized)) return "Father";
    if (["mother", "mom", "female parent"].includes(normalized)) return "Mother";
    return "Guardian";
}

function isPostgresConfigured() {
    return usePostgres;
}

async function ensurePostgresParentFamilyTables() {
    if (!usePostgres) return;
    await postgres.exec(`
        ALTER TABLE users ADD COLUMN IF NOT EXISTS management_role TEXT;
        CREATE TABLE IF NOT EXISTS parents (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            full_name TEXT,
            mobile TEXT UNIQUE,
            email TEXT UNIQUE,
            otp_verified BOOLEAN DEFAULT FALSE,
            status TEXT NOT NULL DEFAULT 'active',
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS parent_student_links (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            parent_id BIGINT NOT NULL REFERENCES parents(id) ON DELETE CASCADE,
            student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
            relationship_type TEXT NOT NULL DEFAULT 'Guardian',
            is_primary BOOLEAN NOT NULL DEFAULT TRUE,
            status TEXT NOT NULL DEFAULT 'active',
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(parent_id, student_id)
        );
        CREATE TABLE IF NOT EXISTS parent_otp_verifications (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            parent_id BIGINT NOT NULL REFERENCES parents(id) ON DELETE CASCADE,
            otp_hash TEXT NOT NULL,
            purpose TEXT NOT NULL,
            expires_at TIMESTAMPTZ NOT NULL,
            attempts INTEGER NOT NULL DEFAULT 0,
            used_at TIMESTAMPTZ,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        );
        ALTER TABLE parent_otp_verifications ADD COLUMN IF NOT EXISTS attempts INTEGER NOT NULL DEFAULT 0;
    `);
}

async function insertOrGetParentAsync({ fullName, mobile, email }) {
    if (!usePostgres) return insertOrGetParent({ fullName, mobile, email });

    const parentMobile = normalizeParentMobile(mobile);
    const parentEmail = normalizeParentEmail(email);
    if (!parentMobile && !parentEmail) return null;

    let parent = parentMobile
        ? await postgres.get("SELECT * FROM parents WHERE mobile = ?", [parentMobile])
        : null;
    if (!parent && parentEmail) {
        parent = await postgres.get("SELECT * FROM parents WHERE email = ?", [parentEmail]);
    }

    if (!parent) {
        parent = await postgres.get(`
            INSERT INTO parents (full_name, mobile, email, otp_verified, status)
            VALUES (?, ?, ?, FALSE, 'active')
            RETURNING *
        `, [fullName || null, parentMobile, parentEmail]);
    } else {
        parent = await postgres.get(`
            UPDATE parents
            SET full_name = COALESCE(?, full_name),
                mobile = COALESCE(?, mobile),
                email = COALESCE(?, email),
                updated_at = CURRENT_TIMESTAMP
            WHERE id = ?
            RETURNING *
        `, [fullName || null, parentMobile || parent.mobile, parentEmail || parent.email, parent.id]);
    }

    return parent;
}

async function ensureParentLinkAsync(parentId, studentId, relationshipType = "Guardian", isPrimary = 1) {
    if (!usePostgres) return ensureParentLink(parentId, studentId, relationshipType, isPrimary);
    return postgres.get(`
        INSERT INTO parent_student_links (parent_id, student_id, relationship_type, is_primary, status)
        VALUES (?, ?, ?, ?, 'active')
        ON CONFLICT (parent_id, student_id) DO UPDATE SET
            relationship_type = EXCLUDED.relationship_type,
            is_primary = EXCLUDED.is_primary,
            status = 'active',
            updated_at = CURRENT_TIMESTAMP
        RETURNING *
    `, [parentId, studentId, normalizeRelationshipType(relationshipType), Number(isPrimary) ? true : false]);
}

